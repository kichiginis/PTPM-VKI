class Converter:
    """Класс для преобразования вещественного числа в целое по заданным правилам."""

    @staticmethod
    def do(x: float) -> int:
        """
        Преобразует вещественное число в целое по диапазонам.

        x ∈ [100.7; +∞)        -> 1000
        x ∈ (0; 100.7)         -> int(x)
        x == 0.0               -> ValueError
        x ∈ [-30.4; 0)         -> int(x) - 5
        x ∈ (-∞; -30.5]        -> -2000
        """
        # 1. x == 0.0 -> исключение
        if x == 0.0:
            raise ValueError("Число не может быть нулём")

        # 2. x >= 100.7 -> 1000
        if x >= 100.7:
            return 1000

        # 3. 0 < x < 100.7 -> int(x)
        if x > 0:
            return int(x)

        # 4. -30.4 <= x < 0 -> int(x) - 5
        if x >= -30.4:
            return int(x) - 5

        # 5. x <= -30.5 -> -2000
        return -2000